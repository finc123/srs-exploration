CREATE OR REPLACE TEMPORARY TABLE SRS_MCP.SANDBOX.FC_OA_HDR AS
SELECT subject_id, subject, from_addr, REGEXP_REPLACE(REGEXP_REPLACE(subject, '[0-9]+', '#'), '\s+', ' ') subj_n
FROM SHARE_NIQ.SRS.SUPRA_QUALITY_MERCHANT_EMAIL_HEADER WHERE domain='openai';
SELECT from_addr, subj_n, COUNT(*) n_subj FROM SRS_MCP.SANDBOX.FC_OA_HDR GROUP BY 1,2 ORDER BY 3 DESC LIMIT 60
