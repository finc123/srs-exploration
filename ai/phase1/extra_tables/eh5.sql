WITH h AS (SELECT DISTINCT order_id FROM SHARE_NIQ.SRS.EMAIL_HEADER WHERE merchant_id=5 AND order_date BETWEEN '2026-08-01' AND '2026-08-31'),
e AS (SELECT DISTINCT order_id FROM SHARE_NIQ.SRS.ITEMS_EXTENDED WHERE merchant_id=5 AND order_date BETWEEN '2026-07-15' AND '2026-09-15')
SELECT (SELECT COUNT(*) FROM h) eh_orders, (SELECT COUNT(*) FROM h JOIN e USING(order_id)) eh_in_ie,
       (SELECT COUNT(*) FROM e) ie_orders
